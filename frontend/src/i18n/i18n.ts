const STORAGE_KEY = 'aakar_language';



const listeners = new Set<() => void>();



let currentLanguage: LanguageCode = loadInitialLanguage();



function loadInitialLanguage(): LanguageCode {

  if (typeof window === 'undefined') {

    return 'en';

  }



  const stored = window.localStorage.getItem(STORAGE_KEY);



  return LANGUAGE_OPTIONS.some((item) => item.code === stored)

    ? (stored as LanguageCode)

    : 'en';

}



export function getLanguage(): LanguageCode {

  return currentLanguage;

}



export function setLanguage(language: LanguageCode): void {

  currentLanguage = language;



  if (typeof window !== 'undefined') {

    window.localStorage.setItem(STORAGE_KEY, language);



    const option = LANGUAGE_OPTIONS.find(

      (item) => item.code === language,

    );



    document.documentElement.lang = language;

    document.documentElement.dir = option?.dir ?? 'ltr';

  }



  listeners.forEach((listener) => listener());

}



function subscribe(listener: () => void): () => void {

  listeners.add(listener);



  return () => {

    listeners.delete(listener);

  };

}



